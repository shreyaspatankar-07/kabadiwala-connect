"""Automatic DATASET_CARD.md documentation generator from pipeline statistics."""

from collections.abc import Sequence
from datetime import UTC, datetime
from pathlib import Path

import numpy as np

from app.data_pipeline.schemas import (
    CleanedPriceObservation,
    DatasetQualityMetrics,
    RollingBoardRate,
)


class DatasetCardGenerator:
    """Generates an up-to-date, transparent /docs/DATASET_CARD.md document from pipeline data."""

    @staticmethod
    def generate_card(
        cleaned_records: Sequence[CleanedPriceObservation],
        rolling_rates: Sequence[RollingBoardRate],
        metrics: DatasetQualityMetrics,
        output_path: Path | None = None,
    ) -> str:
        dest_path = (
            output_path
            or Path(__file__).resolve().parent.parent.parent.parent / "docs" / "DATASET_CARD.md"
        )
        dest_path.parent.mkdir(parents=True, exist_ok=True)

        now_str = datetime.now(UTC).strftime("%Y-%m-%d %H:%M:%S UTC")

        # Category distribution and statistics
        cat_stats: dict[str, list[float]] = {}
        for r in cleaned_records:
            cat_stats.setdefault(r.category, []).append(r.normalized_price_per_kg)

        category_rows = []
        for cat, prices in sorted(cat_stats.items()):
            arr = np.array(prices)
            p_min = np.min(arr)
            p25 = np.percentile(arr, 25)
            med = np.median(arr)
            p75 = np.percentile(arr, 75)
            p_max = np.max(arr)
            row_str = (
                f"| `{cat}` | {len(prices)} | ₹{p_min:.1f} | ₹{p25:.1f} | "
                f"**₹{med:.1f}** | ₹{p75:.1f} | ₹{p_max:.1f} |"
            )
            category_rows.append(row_str)
        category_table = "\n".join(category_rows)

        # District distribution
        district_counts: dict[str, int] = {}
        for r in cleaned_records:
            district_counts[r.district] = district_counts.get(r.district, 0) + 1

        district_rows = [
            f"| **{dist}** | {cnt} | {round((cnt / max(len(cleaned_records), 1)) * 100, 1)}% |"
            for dist, cnt in sorted(district_counts.items(), key=lambda x: -x[1])
        ]
        district_table = "\n".join(district_rows)

        # Active rolling board snippet
        board_rows = [
            f"| `{b.district}` | `{b.category}` | `{b.sub_category}` | "
            f"₹{b.median_7d_per_kg} | `{b.trend}` ({b.pct_change_7d:+0.1f}%) | "
            f"{b.quality_score}/100 |"
            for b in rolling_rates[:10]
        ]
        board_table = "\n".join(board_rows) if board_rows else "| None | - | - | - | - | - |"

        markdown_content = f"""# Dataset Card: Kabadiwala Connect E-Waste Pricing Benchmark

> **Living Dataset Documentation**  
> Automatically generated by the Kabadiwala Connect Data Pipeline on **{now_str}**.  
> **Problem Statement:** Smart India Hackathon PS 26229 (Ministry of Mines / JNARDDC).

---

## 1. Dataset Summary & Motivation

The **Kabadiwala Connect E-Waste Pricing Benchmark Dataset** is an empirical and
simulated time-series dataset designed to bridge information asymmetry between
informal scrap collectors (*kabadiwalas*) and authorized recyclers operating
under India's **E-Waste (Management) Rules, 2022**.

The dataset provides localized, seasonal, and quality-audited benchmark prices
for key e-waste streams across target districts of Maharashtra.

- **Primary Geographies:** Mumbai, Thane, Palghar, Pune, Nashik, Nagpur.
- **Total Valid Records:** {metrics.clean_count:,}
- **Overall Data Quality Score:** **{metrics.overall_quality_score} / 100**
- **Validity Rate:** {metrics.validity_rate_pct}%
- **Freshness Score:** {metrics.freshness_score} / 100

---

## 2. Dataset Structure & Fields

| Field | Type | Description | Privacy / Handling |
| :--- | :--- | :--- | :--- |
| `observation_id` | `string (UUID)` | Unique identifier for observation | System internal |
| `category` | `string` | High-level e-waste material stream | Standardized |
| `sub_category` | `string` | Specific component / dismantled part | Standardized |
| `district` | `string` | Maharashtra district | Standardized |
| `city` | `string` | City / sub-district municipality | Imputed if missing |
| `latitude` | `float` | Geographic latitude | Coarsened to ~500m in exports |
| `longitude` | `float` | Geographic longitude | Coarsened to ~500m in exports |
| `normalized_price_per_kg` | `float` | Price in INR normalized to per-kg | Target feature |
| `weight_kg` | `float` | Sample lot weight in kg | Sanity-bounded |
| `collector_id` | `string` | Submitting informal collector ID | Salted HMAC hashed |
| `recycler_id` | `string` | Associated authorized recycler | Public CPCB identifier |
| `source` | `string` | Provenance (synthetic, survey, quote, tx) | Provenance tagged |
| `recorded_at` | `ISO 8601` | Timestamp of observation | Clock-drift validated |

---

## 3. Data Distribution by Category

Prices normalized to INR per kilogram:

| Category | Sample Size | Min (INR) | P25 (INR) | Median (INR) | P75 (INR) | Max (INR) |
| :--- | :--- | :--- | :--- | :--- | :--- | :--- |
{category_table}

---

## 4. Geographic Distribution (Maharashtra Districts)

| District | Sample Count | Percentage |
| :--- | :--- | :--- |
{district_table}

---

## 5. Sample Rolling Price Board

Recent 7-day rolling medians and trend signals (First 10 entries):

| District | Category | Sub-Category | 7d Median / kg | Trend (7d Δ) | Score |
| :--- | :--- | :--- | :--- | :--- | :--- |
{board_table}

---

## 6. Data Quality, Validation & Quarantine Metrics

The dataset pipeline enforces automated multi-stage validation and outlier handling:

- **Total Ingested Observations:** {metrics.total_raw_ingested:,}
- **Passed Domain Validation:** {metrics.valid_count:,}
- **Quarantined (Validation Rules):** {metrics.quarantined_validation_count:,}
- **Quarantined (Statistical Outliers):** {metrics.quarantined_outlier_count:,}
- **Cleaned Analytical Samples:** {metrics.clean_count:,}
- **Completeness Score:** {metrics.completeness_score}%

### Validation Rules Enforced
1. **Positivity:** Strictly `price > 0`.
2. **Unit Validity:** Standardized to `kg` or `piece`.
3. **Geographic Sanity:** Bounded within India (`8.0°N - 37.5°N`, `68.0°E - 97.5°E`).
4. **Weight Bounds:** Physical sanity constraints per category (e.g. CRT 5-40 kg).
5. **Temporal Integrity:** Rejection of future timestamps (`> now + 5 min`).
6. **Outlier Quarantine:** Double-filter using IQR and MAD (Robust Z-score > 4.5).

---

## 7. Privacy, Ethical Considerations & Anonymization

In strict adherence to the project's **Data Minimization Non-Negotiable Principle**:
- **Zero PII:** No Aadhaar numbers, names, phone numbers, or addresses are captured.
- **Salted Collector ID Hashing:** Collector IDs are transformed with SHA-256 (`ANON-C-<HASH>`).
- **Spatial Grid Coarsening:** GPS coordinates are snapped to a ~500m grid (`0.005°` resolution).

---

## 8. Pipeline CLI Usage

```bash
# Generate synthetic prices and ingest real database activity
make data-seed

# Validate and clean records, routing anomalies to /data/quarantine
make data-validate

# Export privacy-preserved ML datasets to /data/exports/
make data-export
```
"""
        with open(dest_path, "w", encoding="utf-8") as f:
            f.write(markdown_content)

        return str(dest_path)
